"""Property-based tests for the two places arbitrary text reaches a regex.

`hints.classify` runs over whatever Fusion puts in an exception message — which
includes user-authored names, paths and geometry expressions — and its rules are
regexes. A pattern that raises, or a classification that depends on call order,
would turn one bad message into a broken error envelope.

The socket's line framing is exercised with generated byte soup for the same
reason: it must never raise, whatever a client sends.
"""

from __future__ import annotations

import json

import pytest

# hypothesis is a declared dev dependency (pyproject [dependency-groups]); the
# checker here resolves imports against its own environment, not this repo's .venv.
from hypothesis import given, settings  # pyright: ignore[reportMissingImports]
from hypothesis import strategies as st  # pyright: ignore[reportMissingImports]

from fusion360_mcp.hints import classify

TEXT = st.text(max_size=200)
NOISY = st.text(alphabet=st.characters(blacklist_categories=("Cs",)), max_size=200)


class TestClassifyProperties:
    @settings(max_examples=300, deadline=None)
    @given(text=TEXT)
    def test_never_raises_and_returns_a_well_formed_result(self, text):
        result = classify(text)

        assert isinstance(result, tuple) and len(result) == 2
        kind, hints = result
        assert isinstance(kind, str) and kind
        assert isinstance(hints, list)
        assert all(isinstance(h, str) and h for h in hints)

    @settings(max_examples=300, deadline=None)
    @given(text=TEXT)
    def test_hints_accompany_every_known_kind(self, text):
        """UNKNOWN carries no hints; anything the table matched must carry some."""
        kind, hints = classify(text)

        if kind == "UNKNOWN":
            assert hints == []
        else:
            assert hints, f"{kind} matched without hints"

    @settings(max_examples=200, deadline=None)
    @given(text=TEXT)
    def test_classification_is_deterministic(self, text):
        assert classify(text) == classify(text)

    @pytest.mark.parametrize(
        "message,kind",
        [
            ("no profiles in sketch", "PROFILE_NOT_CLOSED"),
            ("no active design", "NO_ACTIVE_DESIGN"),
            ("Body 'Body7' not found", "BODY_NOT_FOUND"),
            ("Sketch 'Sketch1' not found", "SKETCH_NOT_FOUND"),
            ("Body 'Sketch1' not found", "BODY_NOT_FOUND"),
            ("Sketch 'Body1' not found", "SKETCH_NOT_FOUND"),
            ("operation timeout after 30s", "TIMEOUT"),
            (
                "AutoConstrain is not available since user is restricted",
                "NOT_ENTITLED",
            ),
        ],
    )
    def test_known_messages_classify_exactly(self, message, kind):
        """Including the case where a body is *named* after the other kind.

        Found by the property below: `sketch.*not found` used to span the whole
        message, so `Body 'Sketch1' not found` came back as SKETCH_NOT_FOUND.
        """
        assert classify(message)[0] == kind

    @settings(max_examples=300, deadline=None)
    @given(noise=NOISY)
    def test_arbitrary_text_around_a_phrase_still_gets_classified(self, noise):
        """Surrounding text must not push a real failure into UNKNOWN.

        The exact kind is deliberately not asserted: the table is
        first-match-wins, so text carrying two triggers is decided by rule order.
        """
        assert classify(f"{noise} operation timeout after 30s {noise}")[0] != "UNKNOWN"

    @settings(max_examples=200, deadline=None)
    @given(text=TEXT)
    def test_classify_accepts_exceptions_the_same_way(self, text):
        from_exc = classify(RuntimeError(text))
        from_str = classify(text) if text else classify("RuntimeError")
        assert from_exc[0] == from_str[0]


class TestSocketFramingProperties:
    """The framing loop must survive arbitrary bytes without raising."""

    @settings(max_examples=100, deadline=None)
    @given(blob=st.binary(max_size=400))
    def test_arbitrary_bytes_never_raise_in_framing(self, blob):
        # The add-in splits its buffer on newlines and only parses complete
        # lines; model exactly that contract here.
        buffer = blob
        while b"\n" in buffer:
            line, buffer = buffer.split(b"\n", 1)
            try:
                json.loads(line.decode("utf-8"))
            except (ValueError, UnicodeDecodeError):
                # A malformed complete line is a protocol error the caller
                # handles by closing the connection — never an exception here.
                continue
